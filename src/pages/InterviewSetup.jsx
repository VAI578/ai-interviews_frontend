import { useState } from 'react'
import { Link, useNavigate } from 'react-router-dom'
import { createInterview } from '../services/api.js'

const questionIdeas = [
  (role) => `Tell me about yourself and why you're interested in the ${role} role.`,
  (role) => `What is a project or accomplishment related to ${role} that you're proud of?`,
  () => 'Tell me about a challenge you faced at work and how you handled it.',
]

export default function InterviewSetup() {
  const navigate = useNavigate()
  const [role, setRole] = useState('')
  const [level, setLevel] = useState('mid-level')
  const [type, setType] = useState('mixed')
  const [error, setError] = useState('')
  const [saving, setSaving] = useState(false)

  async function handleSubmit(event) {
    event.preventDefault()
    setError('')
    setSaving(true)
    try {
      const interview = await createInterview({
        role: role.trim(),
        experience_level: level,
        interview_type: type,
        questions: questionIdeas.map((makeQuestion) => makeQuestion(role.trim())),
      })
      navigate(`/interview/${interview.id}/live`)
    } catch (requestError) {
      setError(requestError.message)
    } finally {
      setSaving(false)
    }
  }

  return (
    <>
      <div className="page-heading"><div><h1>Set up your practice</h1><p>Choose what you would like to focus on. You can take it one question at a time.</p></div></div>
      <form className="card form-card" onSubmit={handleSubmit}>
        {error && <div className="alert" role="alert">{error}. Make sure the Flask API is running and try again.</div>}
        <div className="form-grid">
          <div className="field full"><label htmlFor="role">Role you are preparing for</label><input id="role" maxLength="120" required value={role} onChange={(event) => setRole(event.target.value)} placeholder="e.g. Product Designer" /><span className="field-hint">Questions will be tailored to the role you enter.</span></div>
          <div className="field"><label htmlFor="level">Experience level</label><select id="level" value={level} onChange={(event) => setLevel(event.target.value)}><option value="entry-level">Entry level</option><option value="mid-level">Mid level</option><option value="senior-level">Senior level</option><option value="lead">Lead / management</option></select></div>
          <div className="field"><label htmlFor="type">Interview style</label><select id="type" value={type} onChange={(event) => setType(event.target.value)}><option value="mixed">Mixed</option><option value="behavioral">Behavioral</option><option value="technical">Technical</option><option value="situational">Situational</option></select></div>
        </div>
        <div className="alert info" style={{ marginTop: 20, marginBottom: 0 }}>This demo creates three practice prompts. The API stores your session and answers; questions are prepared by the frontend, not generated by an AI service.</div>
        <div className="form-actions"><Link className="btn btn-outline" to="/dashboard">Cancel</Link><button className="btn" type="submit" disabled={saving}>{saving ? 'Creating session…' : 'Start practicing →'}</button></div>
      </form>
    </>
  )
}
